#!/usr/bin/env python3
"""
common.py — shared plumbing for the cleaned-dataset training pipeline.

Datasets live (after data_cleaning/clean_build_v4.py) as:

    <data_root>/
      codrone/{train,val,test}/{images,labels}
      visdrone/...
      dota/...
      dataset_all.yaml          (merged train/val/test lists)

Every dataset has the SAME 8-class space, so any Ultralytics OBB model
trained on one evaluates unchanged on the others.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# --------------------------------------------------------------------------
# dataset registry
# --------------------------------------------------------------------------
CLASSES = ["pedestrian", "bicycle", "car", "van", "truck",
           "bus", "tricycle", "motorcyclist"]

REAL_DATASETS = ["codrone", "visdrone", "dota"]
DATASETS = REAL_DATASETS + ["all"]          # 'all' = merged dataset_all.yaml

SPLITS = ["train", "val", "test"]


def resolve_data_root(explicit: str | None = None) -> str:
    """Where the cleaned datasets live. Priority:
    explicit arg > $VEHICLE_OBB_DATA > local NVMe > Colab Drive path > repo-local."""
    if explicit:
        return os.path.abspath(os.path.expanduser(explicit))
    env = os.environ.get("VEHICLE_OBB_DATA")
    if env:
        return os.path.abspath(os.path.expanduser(env))
    local_nvme = "/content/data"
    if os.path.isdir(local_nvme) and os.listdir(local_nvme):
        return local_nvme
    drive = "/content/drive/MyDrive/object-detection/cleaned_data"
    if os.path.isdir(drive):
        return drive
    local = REPO_ROOT / "data" / "cleaned_data"
    return str(local)


def default_runs_dir(explicit: str | None = None) -> str:
    """Where training runs are written. In Colab, default to Drive so
    checkpoints survive runtime disconnects; locally, <repo>/runs."""
    if explicit:
        return os.path.abspath(os.path.expanduser(explicit))
    env = os.environ.get("VEHICLE_OBB_RUNS")
    if env:
        return os.path.abspath(os.path.expanduser(env))
    drive = "/content/drive/MyDrive/object-detection/runs"
    if os.path.isdir("/content/drive/MyDrive"):
        return drive
    return str(REPO_ROOT / "runs")


# --------------------------------------------------------------------------
# dataset yaml handling
# --------------------------------------------------------------------------
def _write_ds_yaml(path: str, ds_root: str, ds: str) -> str:
    with open(path, "w") as f:
        f.write(f"# auto-generated by training/common.py — dataset '{ds}'\n")
        f.write(f"path: {ds_root}\n")
        if ds == "all":
            f.write("train:\n")
            for s in REAL_DATASETS:
                f.write(f"  - {s}/train/images\n")
            f.write("val:\n")
            for s in REAL_DATASETS:
                f.write(f"  - {s}/val/images\n")
            f.write("test:\n")
            for s in REAL_DATASETS:
                f.write(f"  - {s}/test/images\n")
        else:
            f.write("train: train/images\n")
            f.write("val: val/images\n")
            f.write("test: test/images\n")
        f.write("names:\n")
        for i, n in enumerate(CLASSES):
            f.write(f"  {i}: {n}\n")
    return path


def ensure_dataset_yaml(ds: str, data_root: str) -> str:
    """Return an absolute path to a valid Ultralytics dataset.yaml for `ds`,
    creating/refreshing it if needed. Validates the split folders exist."""
    if ds not in DATASETS:
        raise ValueError(f"unknown dataset '{ds}' (choose from {DATASETS})")
    if ds == "all":
        missing = [s for s in REAL_DATASETS
                   if not os.path.isdir(os.path.join(data_root, s, "train", "images"))]
        if missing:
            raise FileNotFoundError(
                f"dataset 'all' needs cleaned datasets on disk, missing: {missing} "
                f"(run data_cleaning/clean_build_v4.py first; root={data_root})")
        return _write_ds_yaml(os.path.join(data_root, "dataset_all.yaml"),
                              data_root, ds)
    for sp in SPLITS:
        d = os.path.join(data_root, ds, sp, "images")
        if not os.path.isdir(d):
            raise FileNotFoundError(
                f"missing split folder: {d} — the cleaned dataset is incomplete "
                "(interrupted Drive copy?). Re-run data_cleaning/clean_build_v4.py.")
    return _write_ds_yaml(os.path.join(data_root, ds, "dataset.yaml"),
                          os.path.join(data_root, ds), ds)


# --------------------------------------------------------------------------
# local staging (Colab: Drive FUSE reads are the epoch-time bottleneck)
# --------------------------------------------------------------------------
def _copy_tree(src: str, dst: str, workers: int = 16) -> tuple[int, int]:
    files = []
    for root, _dirs, fs in os.walk(src):
        for f in fs:
            files.append(os.path.join(root, f))
    if not files:
        return 0, 0

    def cp(s):
        d = os.path.join(dst, os.path.relpath(s, src))
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy2(s, d)
        return 1

    with ThreadPoolExecutor(max_workers=workers) as ex:
        done = sum(ex.map(cp, files))
    return done, len(files)


def stage_local(ds: str, data_root: str, local_root: str | None = None,
                workers: int = 16) -> tuple[str, str]:
    """Copy dataset(s) from slow storage (Drive) to fast local disk.

    Returns (effective_data_root, dataset_yaml_path). Idempotent: an already
    fully-staged dataset is not re-copied.

    v4 (W2): delegates to `training.staging`, which copies atomically
    (.part + os.replace), writes .stage_manifest.json receipts and verifies
    exact byte sizes instead of the old file-count heuristic. The legacy
    signature and return contract are preserved for older callers.
    """
    from training.staging import stage_datasets_blocking

    src_sets = REAL_DATASETS if ds == "all" else [ds]
    local_root = stage_datasets_blocking(
        src_sets, src_root=data_root, dst_root=local_root, workers=workers)
    return local_root, ensure_dataset_yaml(ds, local_root)


