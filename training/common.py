def git_commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             cwd=str(REPO_ROOT), capture_output=True,
                             text=True, timeout=10)
        if out.returncode == 0:
            return out.stdout.strip()
    except Exception:
        pass
    return "unknown"


def write_manifest(run_dir: str, payload: dict) -> str:
    payload = dict(payload)
    payload["timestamp"] = datetime.now(timezone.utc).isoformat()
    payload["git_commit"] = git_commit()
    payload["argv"] = sys.argv
    os.makedirs(run_dir, exist_ok=True)
    p = os.path.join(run_dir, "run_manifest.json")
    with open(p, "w") as f:
        json.dump(payload, f, indent=2)
    return p


def find_weights(run_or_weights: str, prefer: str = "best") -> str:
    """Accept a run directory (-> weights/best.pt, standard Ultralytics
    layout) or a direct weights path."""
    p = run_or_weights
    if os.path.isdir(p):
        order = (["weights/best.pt", "best.pt"] if prefer == "best"
                 else ["weights/last.pt", "last.pt"])
        other = "last" if prefer == "best" else "best"
        for cand in order:
            w = os.path.join(p, cand)
            if os.path.isfile(w):
                return w
        # fall back to whichever exists
        for cand in (f"weights/{other}.pt", f"{other}.pt"):
            w = os.path.join(p, cand)
            if os.path.isfile(w):
                return w
        raise FileNotFoundError(f"no best.pt/last.pt inside {p}")
    if os.path.isfile(p):
        return p
    raise FileNotFoundError(f"no weights or run dir at {p}")


def discover_run_dirs(runs_dir: str, max_depth: int = 3) -> list[str]:
    """All run directories under runs_dir that contain trained weights.
    Handles both <runs_dir>/<name> and <runs_dir>/train/<name> layouts."""
    out = []
    if not os.path.isdir(runs_dir):
        return out
    for root, dirs, _files in os.walk(runs_dir):
        depth = root[len(runs_dir):].count(os.sep)
        if any(os.path.isfile(os.path.join(root, w)) for w in
               ("weights/best.pt", "best.pt")):
            out.append(root)
            dirs[:] = []
        elif depth >= max_depth - 1:
            dirs[:] = []
    return sorted(out)


def human_bytes(n: int) -> str:
    for unit in ["B", "KB", "MB", "GB", "TB"]:
        if n < 1024:
            return f"{n:.1f}{unit}"
        n /= 1024
    return f"{n:.1f}PB"


CURRENT_COORD_SPACE_PREFIX = "original image px"


def protocol_current(res: dict) -> bool:
    """True when an eval result JSON came from the CURRENT unified protocol
    (R3+B1: GT raw in original image coordinates, preds inverse-letterboxed).
    Older coord_space values (e.g. 'letterbox(imgsz)') mixed different GT
    sets per family/imgsz and must never be aggregated with current
    results - cross_eval and summarize_runs skip them with a warning.
    """
    return str(res.get("coord_space", "")).startswith(CURRENT_COORD_SPACE_PREFIX)


def count_instances(ds: str, data_root: str, split: str = "test") -> dict[str, int]:
    """Ground-truth instance count per class for a split (from label files)."""
    sets = REAL_DATASETS if ds == "all" else [ds]
    out = {c: 0 for c in CLASSES}
    for s in sets:
        lbl_d = os.path.join(data_root, s, split, "labels")
        if not os.path.isdir(lbl_d):
            continue
        for f in os.listdir(lbl_d):
            if not f.endswith(".txt"):
                continue
            with open(os.path.join(lbl_d, f)) as fh:
                for ln in fh:
                    t = ln.split()
                    if t and t[0].isdigit() and int(t[0]) < len(CLASSES):
                        out[CLASSES[int(t[0])]] += 1
    return out
